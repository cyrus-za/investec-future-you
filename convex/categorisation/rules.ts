export function lookupMcc(mcc: string | null | undefined): MccRule | null {
  if (!mcc) return null;
  const code = Number.parseInt(mcc, 10);
  if (!Number.isFinite(code)) return null;
  for (const rule of MCC_RULES) {
    if (code >= rule.from && code <= rule.to) return rule;
  }
  return null;
}
