export function isCategory(value: string | null | undefined): value is Category {
  return typeof value === "string" && (CATEGORIES as readonly string[]).includes(value);
}

export type KeywordRule = {
  category: Category;
  /**
   * Whole-word phrases matched against the normalised (uppercased, punctuation
   * stripped) description + merchant name. A phrase can contain spaces.
   */
  keywords: string[];
  /** Only apply when the transaction is a credit/debit. Default: either. */
  direction?: "credit" | "debit";
  /** Confidence to report on a match (0..1). Default 0.85. */
  confidence?: number;
};

