/**
 * Spend categorisation rule table.
 *
 * Everything in this file is DATA, not logic — the matcher lives in
 * `categorise.ts`. Rules are evaluated top-to-bottom and the FIRST match wins,
 * so put specific rules (e.g. "UBER EATS" -> eating_out) above general ones
 * (e.g. "UBER" -> transport_fuel). To add coverage, append keywords to an
 * existing rule or insert a new rule at the right precedence; no code change
 * is needed. See docs/spend-categorisation.md for the full precedence order.
 */

